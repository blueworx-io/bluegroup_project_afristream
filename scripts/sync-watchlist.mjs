// Syncs Editor Picks from an IMDb watchlist into data/editor-picks-ids.txt.
//
// IMDb's watchlist page is behind AWS WAF and returns an empty challenge to a
// plain server fetch, so this uses a real browser (Playwright) to render it and
// read the ordered title IDs from the page's __NEXT_DATA__. Because the plugin
// is built and zipped for manual deploy, this runs at build/deploy time, not on
// the live WordPress server. Run whenever the watchlist changes:
//
//   npm run sync-watchlist
//
// The watchlist URL comes from the IMDB_WATCHLIST_URL env var, falling back to
// DEFAULT_URL below. On success it overwrites data/editor-picks-ids.txt; if no
// IDs are found it exits non-zero and leaves the existing file untouched.
//
// Note: reads the IDs embedded in the initial page render — comfortably covers a
// normal watchlist; a very large one (hundreds) that lazy-loads further pages
// would need scroll-pagination added here.

import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const DEFAULT_URL = 'https://www.imdb.com/user/p.oaowjxrmiacczaqrabkib5cpdi/watchlist/?ref_=ext_shr_lnk';
const WATCHLIST_URL = process.env.IMDB_WATCHLIST_URL || DEFAULT_URL;
const OUT = join(process.cwd(), 'data', 'editor-picks-ids.txt');

const HEADER = `# Editor Picks — IMDb title IDs, in watchlist order.
#
# AUTO-GENERATED by \`npm run sync-watchlist\` from the configured IMDb watchlist.
# Do not edit by hand; re-run the sync instead. One tt-id per line; lines
# starting with # are comments. The plugin reads this as the default Editor
# Picks list (the WP admin "Editor Picks (IMDb IDs)" box overrides it when set),
# resolving each id through TMDB for artwork. Only the first N (see the read-side
# cap) are used.
`;

// Runs in the browser: ordered, deduped title IDs. The rendered list carries
// every item (the SSR __NEXT_DATA__ only holds the first page), so read it from
// the list rows; fall back to __NEXT_DATA__ then any title link if the markup
// ever changes.
function extractIds() {
  const ids = [];
  const seen = new Set();
  const push = (id) => { if (/^tt\d+$/.test(id) && !seen.has(id)) { seen.add(id); ids.push(id); } };

  const rows = document.querySelectorAll('li.ipc-metadata-list-summary-item');
  for (const li of rows) {
    const a = li.querySelector('a[href*="/title/tt"]');
    const m = a && (a.getAttribute('href') || '').match(/\/title\/(tt\d+)/);
    if (m) push(m[1]);
  }
  if (ids.length) return ids;

  const nd = document.getElementById('__NEXT_DATA__');
  if (nd) {
    try {
      const data = JSON.parse(nd.textContent);
      const walk = (o, depth) => {
        if (!o || typeof o !== 'object' || depth > 40) return;
        if (Array.isArray(o)) { for (const v of o) walk(v, depth + 1); return; }
        if (typeof o.id === 'string' && /^tt\d+$/.test(o.id) && (o.titleText || o.titleType || o.releaseYear)) push(o.id);
        for (const k in o) walk(o[k], depth + 1);
      };
      walk(data, 0);
    } catch { /* streaming/incomplete JSON — fall through */ }
  }
  if (!ids.length) {
    for (const a of document.querySelectorAll('a[href*="/title/tt"]')) {
      const m = (a.getAttribute('href') || '').match(/\/title\/(tt\d+)/);
      if (m) push(m[1]);
    }
  }
  return ids;
}

async function main() {
  console.log(`Syncing IMDb watchlist:\n  ${WATCHLIST_URL}`);
  const browser = await chromium.launch();
  try {
    // A realistic user-agent/locale/viewport is what gets us past IMDb's WAF —
    // the default headless "HeadlessChrome" UA is challenged and never resolves.
    const context = await browser.newContext({
      userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0 Safari/537.36',
      locale: 'en-US',
      viewport: { width: 1280, height: 900 },
    });
    const page = await context.newPage();
    await page.goto(WATCHLIST_URL, { waitUntil: 'domcontentloaded', timeout: 60000 });
    // Wait for the WAF challenge to clear and the list to start rendering.
    await page.waitForFunction(
      () => /Watchlist/i.test(document.title) &&
        document.querySelectorAll('li.ipc-metadata-list-summary-item').length > 0,
      null,
      { timeout: 60000 }
    );
    // Scroll to the bottom until the rendered row count reaches the list total,
    // so lazy-loaded rows are all in the DOM before reading. Tolerate append lag
    // by only giving up after several consecutive no-growth checks.
    let prev = -1;
    let stalls = 0;
    for (let i = 0; i < 40; i++) {
      const { rows, total } = await page.evaluate(() => {
        const totalEl = document.querySelector('[data-testid="list-page-mc-total-items"]');
        const total = totalEl ? Number((totalEl.textContent.match(/\d+/) || [])[0]) : 0;
        return { rows: document.querySelectorAll('li.ipc-metadata-list-summary-item').length, total };
      });
      if (total && rows >= total) break;
      stalls = rows === prev ? stalls + 1 : 0;
      if (stalls >= 5) break; // no total available and growth has stopped
      prev = rows;
      await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
      await page.waitForTimeout(1200);
    }
    const ids = await page.evaluate(extractIds);
    if (!ids.length) {
      console.error('No title IDs found on the page — leaving the existing list untouched.');
      process.exitCode = 1;
      return;
    }
    writeFileSync(OUT, HEADER + ids.join('\n') + '\n');
    console.log(`Wrote ${ids.length} title IDs to data/editor-picks-ids.txt`);
  } finally {
    await browser.close();
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
